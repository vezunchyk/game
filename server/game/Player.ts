import { Dir } from "../../shared/constants.js";

export class Player {
  /** Позиція ніг у світових (екранних) координатах. Змінює ТІЛЬКИ сервер. */
  x: number;
  y: number;
  /** Поверх гравця (1, 2, 3...). Колізії перевіряються лише по ньому. */
  floor = 1;
  /** Чи стояв гравець у зоні переходу минулого тіка (щоб міняти поверх лише при вході). */
  inTransition = false;
  /** Індекс сходів, на яких гравець зараз (зайшов з одного з кінців), або -1. */
  stair = -1;
  dir: number = Dir.S;
  moving = false;

  /** Останній намір від клієнта (вже очищений від сміття). Це СТАН, не команда. */
  inputX = 0;
  inputY = 0;
  /** Коли прийшов останній input (для автоматичної зупинки, якщо зв'язок пропав). */
  inputAt = 0;

  constructor(
    public readonly id: number,
    public readonly nick: string,
    x: number,
    y: number,
  ) {
    this.x = x;
    this.y = y;
  }
}
